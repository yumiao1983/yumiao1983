def table(doc, headers, rows, widths, font=9.5):
    t=doc.add_table(rows=1, cols=len(headers)); t.style='Table Grid'; set_table_geometry(t,widths)
    for c,txt in zip(t.rows[0].cells,headers):
        set_cell_shading(c,LIGHT); p=c.paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_after=Pt(0); add_text(p,txt,font,True,INK)
    set_repeat_table_header(t.rows[0])
    for row in rows:
        cells=t.add_row().cells
        prevent_row_split(t.rows[-1])
        for c,txt in zip(cells,row):
            p=c.paragraphs[0]; p.paragraph_format.space_after=Pt(0); p.paragraph_format.line_spacing=1.15; add_text(p,str(txt),font)
    para(doc,'',after=3)
    return t

def flow(doc, title, steps):
    para(doc,title,before=4,after=4,bold=True,size=10.5,color=DARK,keep=True)
    p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_after=Pt(7); p.paragraph_format.line_spacing=1.1
    for i,s in enumerate(steps):
        r=p.add_run(s); run_font(r,9.5,True,'FFFFFF'); r.font.highlight_color = None
        r._element.get_or_add_rPr().append(OxmlElement('w:shd')); r._element.rPr[-1].set(qn('w:fill'), BLUE if i%2==0 else DARK)
        if i < len(steps)-1: add_text(p,'  →  ',9,True,MUTED)

