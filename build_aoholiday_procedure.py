def set_cell_shading(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr(); shd = tcPr.find(qn('w:shd'))
    if shd is None:
        shd = OxmlElement('w:shd'); tcPr.append(shd)
    shd.set(qn('w:fill'), fill)

def set_cell_margin(cell, top=80, start=120, bottom=80, end=120):
    tc = cell._tc; tcPr = tc.get_or_add_tcPr(); tcMar = tcPr.first_child_found_in('w:tcMar')
    if tcMar is None:
        tcMar = OxmlElement('w:tcMar'); tcPr.append(tcMar)
    for m, v in [('top',top), ('start',start), ('bottom',bottom), ('end',end)]:
        node = tcMar.find(qn(f'w:{m}'))
        if node is None:
            node = OxmlElement(f'w:{m}'); tcMar.append(node)
        node.set(qn('w:w'), str(v)); node.set(qn('w:type'), 'dxa')

def set_cell_width(cell, width):
    tcPr = cell._tc.get_or_add_tcPr(); tcW = tcPr.find(qn('w:tcW'))
    if tcW is None:
        tcW = OxmlElement('w:tcW'); tcPr.append(tcW)
    tcW.set(qn('w:w'), str(width)); tcW.set(qn('w:type'), 'dxa')

def set_repeat_table_header(row):
    trPr = row._tr.get_or_add_trPr(); el = OxmlElement('w:tblHeader'); el.set(qn('w:val'), 'true'); trPr.append(el)

def prevent_row_split(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement('w:cantSplit')
    trPr.append(el)

def set_keep_with_next(paragraph):
    paragraph.paragraph_format.keep_with_next = True

def set_table_borders(table, color='B7C3D0'):
    tblPr = table._tbl.tblPr; borders = tblPr.first_child_found_in('w:tblBorders')
    if borders is None:
        borders = OxmlElement('w:tblBorders'); tblPr.append(borders)
    for edge in ('top','left','bottom','right','insideH','insideV'):
        tag = qn('w:'+edge); el = borders.find(tag)
        if el is None:
            el = OxmlElement('w:'+edge); borders.append(el)
        el.set(qn('w:val'),'single'); el.set(qn('w:sz'),'6'); el.set(qn('w:space'),'0'); el.set(qn('w:color'),color)

def set_table_geometry(table, widths):
    table.autofit = False; table.alignment = WD_TABLE_ALIGNMENT.LEFT
    tblPr = table._tbl.tblPr
    tblW = tblPr.first_child_found_in('w:tblW')
    if tblW is None: tblW = OxmlElement('w:tblW'); tblPr.append(tblW)
    tblW.set(qn('w:w'), str(sum(widths))); tblW.set(qn('w:type'),'dxa')
    tblInd = tblPr.first_child_found_in('w:tblInd')
    if tblInd is None: tblInd = OxmlElement('w:tblInd'); tblPr.append(tblInd)
    tblInd.set(qn('w:w'),'120'); tblInd.set(qn('w:type'),'dxa')
    grid = table._tbl.tblGrid
    for gc, w in zip(grid.gridCol_lst, widths): gc.set(qn('w:w'), str(w))
    for row in table.rows:
        prevent_row_split(row)
        for cell, w in zip(row.cells, widths):
            set_cell_width(cell,w); set_cell_margin(cell); cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    set_table_borders(table)

def run_font(run, size=10.5, bold=False, color='000000'):
    run.font.name = FONT; run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT); run._element.rPr.rFonts.set(qn('w:ascii'), 'Calibri'); run._element.rPr.rFonts.set(qn('w:hAnsi'), 'Calibri')
    run.font.size = Pt(size); run.bold = bold; run.font.color.rgb = RGBColor.from_string(color)

def add_text(p, text, size=10.5, bold=False, color='000000'):
    r = p.add_run(text); run_font(r,size,bold,color); return r

def para(doc, text='', style=None, before=0, after=6, align=None, bold=False, size=10.5, color='000000', keep=False):
    p = doc.add_paragraph(style=style) if style else doc.add_paragraph()
    pf=p.paragraph_format; pf.space_before=Pt(before); pf.space_after=Pt(after); pf.line_spacing=1.25
    if align is not None: p.alignment=align
    if text: add_text(p,text,size,bold,color)
    if keep: set_keep_with_next(p)
    return p

def h(doc, text, level=1):
    p=doc.add_paragraph(style=f'Heading {level}')
    p.paragraph_format.keep_with_next=True
    add_text(p,text,{1:16,2:13,3:12}[level],True, BLUE if level<3 else DARK)
    return p

def bullets(doc, items, indent=0):
    for item in items:
        p=doc.add_paragraph(style='List Bullet')
        p.paragraph_format.left_indent=Inches(.375+indent*.2); p.paragraph_format.first_line_indent=Inches(-.188); p.paragraph_format.space_after=Pt(4); p.paragraph_format.line_spacing=1.25
        add_text(p,item)

